//! `cargo xtask client`: regenerates `agentdeck-client`'s `src/generated.rs` from
//! `openapi.json` with progenitor. The output is checked in; a unit test fails while it's
//! stale.

use std::io::Write;
use std::process::{Command, Stdio};

use anyhow::{Context, bail};

/// Where the generated client lives, relative to the workspace root.
const GENERATED: &str = "crates/agentdeck-client/src/generated.rs";

/// Schemas the client takes from `agentdeck-core` instead of generating: the ids, the
/// column enums (both `Display` and `FromStr`) and the layout tree.
const CORE_TYPES: &[&str] = &[
    "WorkspaceId",
    "TabId",
    "PaneId",
    "TaskId",
    "CommentId",
    "InstructionId",
    "CommentAuthor",
    "TaskStatus",
    "TaskKind",
    "PrState",
    "ChecksState",
    "ReviewState",
    "PaneKind",
    "Agent",
    "AgentState",
    "SplitDirection",
    "Layout",
];

const HEADER: &str = "// @generated by `cargo xtask client` from openapi.json. Do not edit.\n\n";

/// Regenerates the client from the committed `openapi.json`.
pub fn run() -> anyhow::Result<()> {
    let root = crate::workspace_root();
    let spec = std::fs::read_to_string(root.join("openapi.json"))
        .context("reading openapi.json; run `cargo xtask openapi` first")?;
    let path = root.join(GENERATED);
    std::fs::write(&path, generate(&spec)?)
        .with_context(|| format!("writing {}", path.display()))?;
    eprintln!("xtask client: wrote {}", path.display());
    Ok(())
}

/// The client source for an OpenAPI document: progenitor's builder-style client, printed by
/// prettyplease and formatted by the pinned toolchain's rustfmt, so `cargo fmt` leaves it be.
pub fn generate(spec: &str) -> anyhow::Result<String> {
    let spec: openapiv3::OpenAPI = serde_json::from_str(spec).context("parsing openapi.json")?;
    let mut settings = progenitor::GenerationSettings::new();
    settings
        .with_interface(progenitor::InterfaceStyle::Builder)
        .with_derive("PartialEq");
    for name in CORE_TYPES {
        let impls = if *name == "Layout" {
            vec![]
        } else {
            vec![progenitor::TypeImpl::Display, progenitor::TypeImpl::FromStr]
        };
        settings.with_replacement(name, format!("agentdeck_core::{name}"), impls.into_iter());
    }
    let tokens = progenitor::Generator::new(&settings)
        .generate_tokens(&spec)
        .context("generating the client")?;
    let file: syn::File = syn::parse2(tokens).context("parsing the generated client")?;
    let source = format!("{HEADER}{}", line_docs(&prettyplease::unparse(&file)));
    rustfmt(&source)
}

/// Rewrites prettyplease's `/** … */` doc comments as `///` lines. rustfmt re-indents a block
/// comment's lines but rustdoc then reads the indented ones as code, so the generated
/// `ignore` examples would run, and fail, as doctests.
fn line_docs(source: &str) -> String {
    let mut out = String::with_capacity(source.len());
    let mut rest = source;
    while let Some(start) = rest.find("/**") {
        let Some(len) = rest[start..].find("*/") else {
            break;
        };
        let line_start = rest[..start].rfind('\n').map_or(0, |i| i + 1);
        let indent = &rest[line_start..start];
        out.push_str(&rest[..start]);
        let body = &rest[start + 3..start + len];
        let lines: Vec<String> = body.split('\n').map(|line| format!("///{line}")).collect();
        out.push_str(&lines.join(&format!("\n{indent}")));
        rest = &rest[start + len + 2..];
    }
    out.push_str(rest);
    out
}

fn rustfmt(source: &str) -> anyhow::Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .current_dir(crate::workspace_root())
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("running rustfmt")?;
    child
        .stdin
        .take()
        .expect("piped stdin")
        .write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!(
            "rustfmt failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    String::from_utf8(output.stdout).context("rustfmt printed non-UTF-8")
}

#[cfg(test)]
mod tests {
    use super::*;

    mod line_docs {
        use super::*;

        #[test]
        fn should_turn_a_block_doc_into_line_docs_at_its_indent() {
            let source = "    /**First\n\n```ignore\nx\n```*/\n    pub fn f() {}\n";
            assert_eq!(
                line_docs(source),
                "    ///First\n    ///\n    ///```ignore\n    ///x\n    ///```\n    pub fn f() {}\n"
            );
        }

        #[test]
        fn should_leave_other_code_alone() {
            let source = "/// Already a line doc.\nfn f() { let x = 2 * 3; }\n";
            assert_eq!(line_docs(source), source);
        }
    }

    mod generate {
        use super::*;

        const SPEC: &str = include_str!("../../../openapi.json");
        const COMMITTED: &str = include_str!("../../agentdeck-client/src/generated.rs");

        #[test]
        fn should_match_the_committed_client() {
            let generated = generate(SPEC).unwrap();
            assert!(
                generated == COMMITTED,
                "agentdeck-client is stale: run `cargo xtask client` and commit the result"
            );
        }
    }
}
